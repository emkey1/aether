            return "/tests/atomic_logic32.c";
        case aokfs_tests_signal_core:
            return "/tests/signal_core.c";
        case aokfs_tests_signal_restart:
            return "/tests/signal_restart.c";
        case aokfs_tests_signal_realtime:
            return "/tests/signal_realtime.c";
