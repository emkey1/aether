static const char *aokfs_node_basename(enum aokfs_node_kind node) {
    const char *path = aokfs_node_path(node);
    const char *slash = strrchr(path, '/');
    return slash == NULL ? path : slash + 1;
}

static bool aokfs_lookup_node(const char *path, enum aokfs_node_kind *node_out) {
    static const enum aokfs_node_kind nodes[] = {
        aokfs_root,
        aokfs_readme,
        aokfs_version,
        aokfs_fixes_dir,
        aokfs_fixes_devuan_dir,
        aokfs_fixes_devuan_readme,
        aokfs_fixes_devuan_pkcsslotd_init,
        aokfs_fixes_debian_link,
        aokfs_tests_dir,
        aokfs_tests_readme,
        aokfs_tests_atomics32,
        aokfs_tests_atomic_common,
        aokfs_tests_test_common,
        aokfs_tests_atomic_xadd32,
        aokfs_tests_atomic_cmpxchg32,
        aokfs_tests_atomic_cmpxchg8b,
        aokfs_tests_atomic_logic32,
        aokfs_tests_signal_core,
        aokfs_tests_signal_restart,
        aokfs_tests_signal_realtime,
        aokfs_tests_signal_altstack,
        aokfs_tests_signal_poll,
        aokfs_tests_eventfd_interrupt,
        aokfs_tests_futex_core,
        aokfs_tests_process_lifecycle,
        aokfs_tests_pthread_sync,
        aokfs_tests_setup_regressions,
        aokfs_tests_audio_dir,
        aokfs_audio_raw,
        aokfs_audio_wav,
    };

    for (size_t i = 0; i < sizeof(nodes) / sizeof(nodes[0]); i++) {
        enum aokfs_node_kind node = nodes[i];
        if (strcmp(path, aokfs_node_path(node)) == 0) {
            *node_out = node;
            return true;
        }
    }
    return false;
}

static const char *aokfs_symlink_target(enum aokfs_node_kind node, size_t *size_out) {
    static const char fixes_debian[] = "devuan";

    switch (node) {
        case aokfs_fixes_debian_link:
            *size_out = sizeof(fixes_debian) - 1;
            return fixes_debian;
        default:
            *size_out = 0;
            return "";
    }
}

